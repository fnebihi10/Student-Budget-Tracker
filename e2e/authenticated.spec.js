test('real browser recovery link, recovery screen at every target width, and password replacement', async ({ page }) => {
  const { data, error } = await admin.auth.admin.generateLink({ type: 'recovery', email, options: { redirectTo: 'http://127.0.0.1:4173/?recovery=1' } });
  if (error) throw error;
  await page.goto(data.properties.action_link);
  await expect(page.getByText('Choose a new password', { exact: true })).toBeVisible();
  for (const width of [360, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.screenshot({ path: `test-results/recovery-${width}.png` });
    const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze();
    expect(results.violations).toEqual([]);
  }
  const replacement = `${password}-new`;
  await page.getByLabel('New password', { exact: true }).fill(replacement);
  await page.getByLabel('Confirm new password', { exact: true }).fill('mismatch');
  await expect(page.getByRole('button', { name: 'Save new password', exact: true })).toBeDisabled();
  await page.getByLabel('Confirm new password', { exact: true }).fill(replacement);
  await page.getByRole('button', { name: 'Save new password', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Refresh', exact: true })).toBeVisible();
  const signedIn = await deviceB.auth.signInWithPassword({ email, password: replacement });
  if (signedIn.error) throw signedIn.error;
});
