const { test, expect } = require('@playwright/test');
const { createClient } = require('@supabase/supabase-js');
const { randomUUID } = require('node:crypto');
const { isolatedProject } = require('../scripts/isolated-project.cjs');
const AxeBuilder = require('@axe-core/playwright').default;
const options = { auth: { persistSession: false, autoRefreshToken: false } };
let admin, deviceB, user, email, password;
test.beforeAll(async () => {
  const project = isolatedProject();
  admin = createClient(project.url, project.serviceKey, options);
  deviceB = createClient(project.url, project.publicKey, options);
  email = `pocketwise-browser-${randomUUID()}@example.com`; password = `Pocketwise-${randomUUID()}!`;
  const created = await admin.auth.admin.createUser({ email, password, email_confirm: true });
  if (created.error) throw created.error;
  user = created.data.user;
  const signedIn = await deviceB.auth.signInWithPassword({ email, password });
  if (signedIn.error) throw signedIn.error;
});
test.afterAll(async () => {
  if (user) {
    const { error } = await admin.auth.admin.deleteUser(user.id);
    if (error) throw error;
  }
  if (deviceB) await deviceB.auth.signOut({ scope: 'local' });
});
