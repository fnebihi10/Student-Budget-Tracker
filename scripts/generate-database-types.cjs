const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');

// Offline, reproducible from the checked-in migrations and locked PGlite.
// Auth bootstrap models only the schema needed by migrations, not real Auth.
async function generate() {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users(id uuid primary key, raw_user_meta_data jsonb default '{}');
      create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;`);
    for (const file of fs.readdirSync('supabase/migrations').sort()) {
      await db.exec(fs.readFileSync(path.join('supabase/migrations', file), 'utf8').replace('create extension if not exists pgcrypto;', ''));
    }
    const { rows: columns } = await db.query(`select table_name, column_name, data_type, is_nullable, column_default
      from information_schema.columns where table_schema='public' order by table_name, ordinal_position`);
    const { rows: checks } = await db.query(`select cl.relname as table_name, pg_get_constraintdef(c.oid) as definition
      from pg_constraint c join pg_class cl on cl.oid=c.conrelid join pg_namespace n on n.oid=cl.relnamespace
      where n.nspname='public' and c.contype='c'`);
    const scalar = (type) => {
      if (['numeric', 'bigint', 'integer', 'smallint', 'double precision', 'real'].includes(type)) return 'number';
      if (type === 'boolean') return 'boolean';
      if (type === 'jsonb' || type === 'json') return 'Json';
      if (type === 'void') return 'undefined';
      if (['uuid', 'text', 'timestamp with time zone', 'timestamp without time zone', 'date'].includes(type)) return 'string';
      throw new Error(`Unsupported database type ${type}; extend generator explicitly.`);
    };
    const tableNames = [...new Set(columns.map((c) => c.table_name))];
    const contracts = {};
    const tables = tableNames.map((name) => {
      const fields = columns.filter((c) => c.table_name === name);
      const types = fields.map((c) => {
        let type = scalar(c.data_type);
        const contract = { type: type === 'Json' ? 'json' : type, nullable: c.is_nullable === 'YES' };
        const check = checks.find((v) => v.table_name === name && v.definition.includes(`${c.column_name} = ANY (ARRAY[`));
        if (check) {
          const literals = [...check.definition.matchAll(/'([^']*)'::text/g)].map((m) => JSON.stringify(m[1]));
          if (!literals.length) throw new Error('Unrecognized enum constraint');
          type = literals.join(' | ');
          contract.values = literals.map((v) => JSON.parse(v));
        }
        (contracts[name] ??= {})[c.column_name] = contract;
        return [c, type + (c.is_nullable === 'YES' ? ' | null' : '')];
      });
      const row = types.map(([c, type]) => `${c.column_name}: ${type}`).join('; ');
      const insert = types.map(([c, type]) => `${c.column_name}${c.is_nullable === 'YES' || c.column_default !== null ? '?' : ''}: ${type}`).join('; ');
      return `      ${name}: { Row: { ${row} }; Insert: { ${insert} }; Update: { ${types.map(([c, t]) => `${c.column_name}?: ${t}`).join('; ')} }; Relationships: [] };`;
    });
    const { rows: functions } = await db.query(`select p.proname, pg_get_function_arguments(p.oid) as args,
      pg_get_function_result(p.oid) as result from pg_proc p join pg_namespace n on n.oid=p.pronamespace
      where n.nspname='public' and p.prorettype <> 'trigger'::regtype order by p.proname`);
    const functionsText = functions.map((f) => {
      const field = (v) => { const [name, ...type] = v.trim().split(' '); return `${name}: ${scalar(type.join(' '))}`; };
      const args = f.args ? `{ ${f.args.split(',').map(field).join('; ')} }` : 'Record<never, never>';
      const result = f.result.startsWith('TABLE(') ? `{ ${f.result.slice(6, -1).split(',').map(field).join('; ')} }[]` : scalar(f.result);
      return `      ${f.proname}: { Args: ${args}; Returns: ${result} };`;
    });
    const output = `// Generated by npm run types:database. Do not edit by hand.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = {\n  public: {\n    Tables: {\n${tables.join('\n')}\n    };\n    Views: Record<never, never>;\n    Functions: {\n${functionsText.join('\n')}\n    };\n    Enums: Record<never, never>; CompositeTypes: Record<never, never>;\n  };\n};\nexport type RowOf<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row'];\nexport const rowContracts = ${JSON.stringify(contracts, null, 2)} as const;\n`;
    const target = 'src/services/database.ts';
    if (process.argv.includes('--check')) {
      if (fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Database types drifted. Run npm run types:database and review the diff.');
    } else fs.writeFileSync(target, output);
    console.log('PASS: database types match the migrated PostgreSQL catalog.');
  } finally { await db.close(); }
}
generate().catch((error) => { console.error(error.message); process.exitCode = 1; });
